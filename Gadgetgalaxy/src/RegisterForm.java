    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
        String username = txt_name.getText();
        String email = txt_email.getText();
        String pwd = txt_pwd.getText();
        String role = cmb_role.getSelectedItem().toString();
        
        try{
            FileWriter suser = new FileWriter("user.txt", true);
            
            suser.write(username+","+email+","+role+","+pwd+"\n");
            suser.close();
            JOptionPane.showMessageDialog(this,"user register successfully !!");
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this,"Error saving user");
        }           
    }//GEN-LAST:event_btn_saveActionPerformed

